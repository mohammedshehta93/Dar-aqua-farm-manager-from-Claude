def wait_sync(pg): pg.wait_for_function('() => !!window._cloudSyncDone', timeout=10000); pg.wait_for_timeout(300)
def errs(sb, **kw): return [e for e in getattr(sb, 'errors', []) if all(e.get(k) == v for k, v in kw.items())]
with sync_playwright() as p:
    harness_browser[0] = p.chromium.launch()
    sb = MockSB()
    sb.add_user('owner@example.com','admin123',role='admin',uid='u-admin'); sb.platform.add('u-admin')
    sb.add_user('worker@example.com','work123',role='worker',uid='u-worker')
    ctx, pg = new_page(p, sb)
    login(pg,'owner@example.com','admin123'); wait_sync(pg)
    pg.evaluate("VIEWS['crashtest'] = function(){ throw new Error('boom 123'); }; show('crashtest')"); pg.wait_for_timeout(1500)
    check('E1 crashed page shows friendly message', 'حصلت مشكلة' in content(pg) and 'اتبلّغت' in content(pg))
    r = errs(sb, kind='render')
    check('E1 render error reported with farm/user/page', len(r) == 1 and r[0]['view'] == 'crashtest' and r[0]['farm_id'] == 'farm-main' and r[0]['user_email'] == 'owner@example.com' and 'boom' in r[0]['message'], r)
    pg.evaluate("setTimeout(function(){ throw new Error('uncaught 7'); }, 0)"); pg.wait_for_timeout(1200)
    check('E2 uncaught error reported', len(errs(sb, kind='error')) == 1)
    pg.evaluate("setTimeout(function(){ Promise.reject(new Error('rejected 9')); }, 0)"); pg.wait_for_timeout(1200)
    check('E3 unhandled promise rejection reported', len(errs(sb, kind='promise')) == 1)
    pg.evaluate("VIEWS['crashtest'] = function(){ throw new Error('boom 456'); }; show('crashtest'); show('crashtest')"); pg.wait_for_timeout(1200)
    check('E4 repeats de-duplicated (numbers ignored)', len(errs(sb, kind='render')) == 1, len(errs(sb, kind='render')))
    pg.evaluate("window.dispatchEvent(new ErrorEvent('error', {message:'ResizeObserver loop limit exceeded'}))"); pg.wait_for_timeout(1000)
    check('E5 browser noise ignored', not any('ResizeObserver' in e['message'] for e in getattr(sb, 'errors', [])))
    sb.offline = True
    pg.evaluate("setTimeout(function(){ throw new Error('while offline'); }, 0)"); pg.wait_for_timeout(1200)
    check('E6 offline: kept in queue', 'while offline' in (pg.evaluate("() => localStorage.getItem('daracqua_err_queue')") or '') and not any('offline' in e['message'] for e in sb.errors))
    sb.offline = False; pg.evaluate('daFlushErrors()'); pg.wait_for_timeout(1000)
    check('E6 sent when connection returns', any('while offline' in e['message'] for e in sb.errors) and pg.evaluate("() => localStorage.getItem('daracqua_err_queue')") is None)
    pg.evaluate("console.warn('TX upsert failed:', 'permission denied for table transactions')"); pg.wait_for_timeout(1200)
    check('E7 cloud-sync failure reported', len(errs(sb, kind='sync')) == 1)
    pg.wait_for_timeout(1700)
    check('E10 error queue never synced into farm settings', 'daracqua_err_queue' not in sb.settings.get('farm-main', {}))
    pg.evaluate("show('dashboard')"); pg.wait_for_timeout(300)
    check('E9 app keeps working after a crash', 'مشكلة' not in content(pg) and len(content(pg)) > 50)
    pg.evaluate("show('platform')"); pg.wait_for_timeout(1200)
    panel = pg.inner_text('#pf-errors')
    check('E8 platform owner sees grouped errors with farm name', 'boom' in panel and 'Dar Aqua' in panel and 'uncaught' in panel, panel[:200])
    n_before = pg.evaluate('() => _pfErrors.length')
    pg.evaluate('platformResolveError(0)'); pg.wait_for_timeout(900)
    check('E8 resolve hides the error', pg.evaluate('() => _pfErrors.length') == n_before - 1)
    pg.evaluate('platformTestError()'); pg.wait_for_timeout(3200)
    check('E8 test-error button works end to end', 'Test error' in pg.inner_text('#pf-errors'))
    stored = json.dumps(getattr(sb, 'errors', []))
